//! `gen-r`: a stand-in `R.java` generated from the resource directory.
//!
//! The real `R.java` comes from `aapt2 link --java` in the APK build. The stand-in has the
//! same shape (one class per resource type, one `int` per name) with arbitrary values, so that
//! the Java sources can be compiled against android.jar without the Android build tools: a
//! missing or misspelt resource name then fails compilation here instead of in CI.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;

use crate::dom;
use crate::util::{is_word, list_dir, read_file, read_text, say};

type Types = BTreeMap<String, BTreeSet<String>>;

fn add(types: &mut Types, kind: &str, name: &str) {
    types.entry(kind.to_owned()).or_default().insert(name.to_owned());
}

/// Names of `@+id/name` declarations in `text`.
fn plus_ids(text: &str) -> Vec<&str> {
    let mut out = Vec::new();
    for (i, _) in text.match_indices("@+id/") {
        let rest = text.get(i + "@+id/".len()..).unwrap_or_default();
        let len = rest.chars().take_while(|&c| is_word(c)).map(char::len_utf8).sum::<usize>();
        if let Some(name) = rest.get(..len).filter(|n| !n.is_empty()) {
            out.push(name);
        }
    }
    out
}

/// All resource names of a `res/` tree, by type.
///
/// # Errors
/// Unreadable directories or a `values` file that is not well-formed XML.
pub fn resource_names(res_dir: &Path) -> Result<Types, String> {
    let mut types = Types::new();
    for (entry, path) in list_dir(res_dir)? {
        if !path.is_dir() {
            continue;
        }
        let kind = entry.split('-').next().unwrap_or_default();
        for (fname, fpath) in list_dir(&path)? {
            if kind == "values" {
                if !fname.ends_with(".xml") {
                    continue;
                }
                let root = dom::parse(&read_file(&fpath)?)
                    .map_err(|e| format!("{}: {e}", fpath.display()))?;
                for el in &root.children {
                    let Some(name) = el.attr("name") else { continue };
                    match el.name.as_str() {
                        "item" => {
                            if let Some(t) = el.attr("type") {
                                add(&mut types, t, name);
                            }
                        }
                        t @ ("string" | "color" | "dimen" | "integer" | "bool" | "plurals"
                        | "style" | "attr" | "id") => add(&mut types, t, &name.replace('.', "_")),
                        "string-array" | "array" | "integer-array" => {
                            add(&mut types, "array", name)
                        }
                        "declare-styleable" => add(&mut types, "styleable", name),
                        _ => {}
                    }
                }
            } else {
                let base = fname.split('.').next().unwrap_or_default();
                if !base.is_empty() {
                    add(&mut types, kind, base);
                }
                if fname.ends_with(".xml") {
                    let text = read_text(&fpath)?;
                    for id in plus_ids(&text) {
                        add(&mut types, "id", id);
                    }
                }
            }
        }
    }
    Ok(types)
}

/// The text of the stand-in `R.java`.
#[must_use]
pub fn render(package: &str, types: &Types) -> String {
    let mut lines = vec![
        "// Stand-in R.java for compile checks (generated by arca-devtools gen-r).".to_owned(),
        format!("package {package};"),
        String::new(),
        "public final class R {".to_owned(),
        "    private R() {}".to_owned(),
    ];
    let base: u32 = 0x7F01_0000;
    for (i, (kind, names)) in types.iter().enumerate() {
        lines.push(format!("    public static final class {kind} {{"));
        lines.push(format!("        private {kind}() {{}}"));
        let i = u32::try_from(i).unwrap_or(0);
        for (j, name) in names.iter().enumerate() {
            let value = base.wrapping_add(i << 16).wrapping_add(u32::try_from(j).unwrap_or(0));
            lines.push(format!("        public static final int {name} = 0x{value:08X};"));
        }
        lines.push("    }".to_owned());
    }
    lines.push("}".to_owned());
    lines.join("\n") + "\n"
}

/// Entry point: `gen-r <res-dir> <package> <out-dir>`.
///
/// # Errors
/// Bad arguments, unreadable resources or an unwritable output directory.
pub fn run(args: &[String]) -> Result<(), String> {
    let [res, package, out] = args else {
        return Err("usage: gen-r <res-dir> <package> <out-dir>".into());
    };
    let types = resource_names(Path::new(res))?;
    let mut dir = Path::new(out).to_path_buf();
    for part in package.split('.') {
        dir.push(part);
    }
    fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let file = dir.join("R.java");
    fs::write(&file, render(package, &types)).map_err(|e| format!("{}: {e}", file.display()))?;
    say(&format!("gen-r: {} resource types -> {}", types.len(), file.display()));
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::util::TempDir;

    fn tree() -> TempDir {
        let t = TempDir::new("genr");
        t.write(
            "values/strings.xml",
            "<resources><string name=\"a.b\">x</string><string-array name=\"arr\"><item>1</item></string-array><item name=\"k\" type=\"id\"/><style name=\"Theme.X\"/></resources>",
        );
        t.write("drawable/ic_a.xml", "<vector/>");
        t.write("mipmap-anydpi-v26/ic.xml", "<adaptive-icon/>");
        t.write("xml/locales.xml", "<locale-config id=\"@+id/zed\"/>");
        t
    }

    #[test]
    fn collects_names_by_type() {
        let t = tree();
        let types = resource_names(&t.0).unwrap();
        let get = |k: &str| {
            types.get(k).map(|s| s.iter().cloned().collect::<Vec<_>>()).unwrap_or_default()
        };
        assert_eq!(get("string"), ["a_b"]);
        assert_eq!(get("array"), ["arr"]);
        assert_eq!(get("id"), ["k", "zed"]);
        assert_eq!(get("style"), ["Theme_X"]);
        assert_eq!(get("drawable"), ["ic_a"]);
        assert_eq!(get("mipmap"), ["ic"]);
        assert_eq!(get("xml"), ["locales"]);
    }

    #[test]
    fn renders_deterministic_java() {
        let t = tree();
        let java = render("org.x", &resource_names(&t.0).unwrap());
        assert!(java.starts_with("// Stand-in R.java"));
        assert!(java.contains("package org.x;"));
        assert!(java.contains("public static final int a_b = 0x7F050000;"));
        assert!(java.contains("public static final int ic_a = 0x7F020000;"));
        assert_eq!(java, render("org.x", &resource_names(&t.0).unwrap()));
    }

    #[test]
    fn a_malformed_values_file_is_an_error() {
        let t = TempDir::new("genr-bad");
        t.write("values/s.xml", "<resources><string>");
        assert!(resource_names(&t.0).is_err());
    }
}
