"""Generates a stand-in R.java from the resource directory.

The real R.java comes from `aapt2 link --java` in the APK build. This stand-in has the same
shape (one class per resource type, one int per name) with arbitrary values, so that the Java
sources can be compiled against android.jar without the Android build tools: a missing or
misspelt resource name then fails compilation here instead of in CI.

    gen_r.py RES_DIR PACKAGE OUT_DIR
"""
import os
import re
import sys
import xml.etree.ElementTree as ET


def resource_names(res_dir):
    types = {}

    def add(kind, name):
        types.setdefault(kind, set()).add(name)

    for entry in sorted(os.listdir(res_dir)):
        path = os.path.join(res_dir, entry)
        if not os.path.isdir(path):
            continue
        kind = entry.split("-")[0]
        if kind == "values":
            for fname in sorted(os.listdir(path)):
                if not fname.endswith(".xml"):
                    continue
                root = ET.parse(os.path.join(path, fname)).getroot()
                for el in root:
                    name = el.get("name")
                    if el.tag == "item":
                        add(el.get("type"), name)
                    elif el.tag in ("string", "color", "dimen", "integer", "bool", "plurals", "style", "attr", "id"):
                        add(el.tag, name.replace(".", "_"))
                    elif el.tag == "string-array" or el.tag == "array" or el.tag == "integer-array":
                        add("array", name)
                    elif el.tag == "declare-styleable":
                        add("styleable", name)
        else:
            for fname in sorted(os.listdir(path)):
                base = fname.split(".")[0]
                if base:
                    add(kind, base)
                if fname.endswith(".xml"):
                    text = open(os.path.join(path, fname), encoding="utf-8").read()
                    for m in re.finditer(r'@\+id/([A-Za-z0-9_]+)', text):
                        add("id", m.group(1))
    return types


def main():
    res_dir, package, out_dir = sys.argv[1:4]
    types = resource_names(res_dir)
    os.makedirs(os.path.join(out_dir, *package.split(".")), exist_ok=True)
    lines = ["// Stand-in R.java for compile checks (generated by tools/android/gen_r.py).",
             "package %s;" % package, "", "public final class R {", "    private R() {}"]
    base = 0x7F010000
    for i, kind in enumerate(sorted(types)):
        lines.append("    public static final class %s {" % kind)
        lines.append("        private %s() {}" % kind)
        for j, name in enumerate(sorted(types[kind])):
            lines.append("        public static final int %s = 0x%08X;" % (name, base + (i << 16) + j))
        lines.append("    }")
    lines.append("}")
    with open(os.path.join(out_dir, *package.split("."), "R.java"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
